/** Sentado no banco, perna direita esticada à frente (exercícios de tornozelo com elástico). */
const sentadoPernaEsticada = (extD: number, esforco: number, ate: number, pausa = 0): Pose => ({
  quadril: [0, BANCO + 6],
  tronco: 184,
  pernaD: pe(80, BANCO + 2, extD),
  pernaE: pe(28),
  bracoD: ang(-18, -14, -10),
  bracoE: ang(-18, -14, -10),
  esforco,
  ate,
  pausa,
});

/** Em pé numa perna só (direita), joelho esquerdo à frente; a mão direita pode apoiar na parede. */
const umPe = (dx: number, extra: Partial<Pose> = {}): Pose => ({
  quadril: [dx, 87],
  tronco: 180,
  pernaD: pe(3),
  pernaE: pe(26, 44, 60),
  bracoD: ang(35, 30, 20),
  bracoE: ang(-30, -20, -10),
  ...extra,
});

/** Na ponta dos pés no degrau, com a mão na parede à frente. */
const noDegrau = (ext: number, alt: number, dx: number, extra: Partial<Pose> = {}): Pose => ({
  quadril: [dx, alt],
  tronco: 180,
  pernaD: pePelaPonta(20, DEGRAU, ext),
  pernaE: pePelaPonta(17, DEGRAU, ext),
  bracoD: mao(48, 118, 90),
  bracoE: mao(46, 112, 90),
  ...extra,
});
const PROPS_DEGRAU = [
  { tipo: "caixa" as const, x: 12, y: 0, w: 40, h: DEGRAU },
  { tipo: "parede" as const, x: 60 },
];

/** Deitado de costas (cabeça para -x), joelhos dobrados. */
const deitado = (quadrilY: number, tronco: number, extra: Partial<Pose> = {}): Pose => ({
  quadril: [0, quadrilY],
  tronco,
  cabeca: Math.max(-90, tronco - 12),
  pernaD: pe(38),
  pernaE: pe(38),
  bracoD: ang(90, 90, 90),
  bracoE: ang(90, 90, 90),
  ...extra,
});

/** Salto com os dois pés para a frente e volta andando (vista de lado). */
function saltoParaFrente(distancia: number, alturaVoo: number): Pose[] {
  const pronto: Pose = { ...EM_PE_LADO, esforco: 0.2, ate: 0.8 };
  const agacha: Pose = {
    quadril: [-14, 60],
    tronco: 142,
    cabeca: 160,
    pernaD: pe(3),
    pernaE: pe(-1),
    bracoD: ang(-60, -50, -40),
    bracoE: ang(-60, -50, -40),
    esforco: 0.6,
    ate: 0.25,
  };
  const impulso: Pose = {
    quadril: [10, 92],
    tronco: 160,
    pernaD: pePelaPonta(17, 0, 20),
    pernaE: pePelaPonta(14, 0, 20),
    bracoD: ang(150, 165, 170),
    bracoE: ang(150, 165, 170),
    esforco: 1,
    ate: 0.3,
  };
  const voo: Pose = {
    quadril: [distancia / 2, 92 + alturaVoo],
    tronco: 165,
    pernaD: pe(distancia / 2 + 12, 30 + alturaVoo, 60),
    pernaE: pe(distancia / 2 + 8, 32 + alturaVoo, 60),
    bracoD: ang(110, 120, 120),
    bracoE: ang(110, 120, 120),
    esforco: 0.8,
    ate: 0.3,
  };
  const pousa: Pose = {
    quadril: [distancia - 12, 62],
    tronco: 145,
    pernaD: pe(distancia + 3),
    pernaE: pe(distancia - 1),
    bracoD: ang(60, 80, 80),
    bracoE: ang(60, 80, 80),
    esforco: 1,
    pausa: 1.5,
    ate: 0.8,
  };
  const ergue: Pose = {
    ...EM_PE_LADO,
    quadril: [distancia, 89],
    pernaD: pe(distancia + 3),
    pernaE: pe(distancia - 3),
    esforco: 0.2,
    ate: 0.4,
  };
  return [pronto, agacha, impulso, voo, pousa, ergue, ...voltarAndando(distancia, EM_PE_LADO)];
}

